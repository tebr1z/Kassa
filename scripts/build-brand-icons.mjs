import sharp from 'sharp';
import {mkdir,writeFile} from 'node:fs/promises';
const sizes=[16,32,48,64,128,256];
await mkdir('desktop/assets',{recursive:true});
const images=await Promise.all(sizes.map(size=>sharp('public/restamarket-mark.svg').resize(size,size).png().toBuffer()));
const header=Buffer.alloc(6+16*sizes.length);header.writeUInt16LE(1,2);header.writeUInt16LE(sizes.length,4);
let offset=header.length;
images.forEach((image,index)=>{const entry=6+16*index,size=sizes[index];header[entry]=size===256?0:size;header[entry+1]=size===256?0:size;header.writeUInt16LE(1,entry+4);header.writeUInt16LE(32,entry+6);header.writeUInt32LE(image.length,entry+8);header.writeUInt32LE(offset,entry+12);offset+=image.length;});
await writeFile('desktop/assets/restamarket.ico',Buffer.concat([header,...images]));
await sharp('public/restamarket-mark.svg').resize(512,512).png().toFile('desktop/assets/restamarket.png');
await sharp('public/restamarket-mark.svg').resize(180,180).png().toFile('public/restamarket-apple.png');
console.log('RestaMarket: vector mark, Windows multi-size ICO, desktop PNG and Apple icon ready.');
